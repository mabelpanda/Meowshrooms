using UnityEngine;

// особенность структур в c#: тип-значение, хранит сами данные (в отличие от class - ссылочный тип, хранит ссылку на обьект в куче).
// при передаче и присваивании структура копируется (в отличие от класса, где копируется ссылка)
// здесь выбираем структуру как раз, чтобы передавать копии, и тем самым дополнительно защитить (оригинал) от изменений
// неизменяемая она для того, чтобы случайно не сделать изменения в передаваемой копии, когда хотим в оригинале
// также маленькие значения из двух полей обычно принято делать структурами
public readonly struct ItemStack // слот инвентаря: (неизменяемая) пара предмет + количество
{
    public ItemData Item { get; }
    public int Count { get; }
    public bool IsEmpty => Item == null || Count <= 0;

    // конструктор
    public ItemStack(ItemData  item, int count)
    {
        Item = item;
        Count = count;
    }
}